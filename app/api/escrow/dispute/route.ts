import { NextRequest, NextResponse } from "next/server"
import { prisma } from "@/lib/prisma"
import axios from "axios"
import { sendWhatsAppMessage } from "@/lib/whatsapp"

// Types for dispute payload
interface DisputePayload {
  transactionId: string
  disputeFault: "SELLER_FAULT" | "BUYER_FAULT"
  reason?: string
}

// POST - Dispute & liability arbitration route
export async function POST(request: NextRequest) {
  try {
    const body: DisputePayload = await request.json()
    const { transactionId, disputeFault, reason } = body

    // Validate required fields
    if (!transactionId || !disputeFault) {
      return NextResponse.json(
        { error: "Missing required fields: transactionId, disputeFault" },
        { status: 400 }
      )
    }

    // Find the transaction
    const transaction = await prisma.escrowTransaction.findFirst({
      where: { id: transactionId },
    })

    if (!transaction) {
      return NextResponse.json(
        { error: "Transaction not found" },
        { status: 404 }
      )
    }

    // Ensure transaction is in a state eligible for dispute resolution
    // ESCROW_LOCKED, DISPATCHED, or DELIVERED states can be disputed
    const eligibleStatuses = ["ESCROW_LOCKED", "DISPATCHED", "DELIVERED"]
    if (!eligibleStatuses.includes(transaction.status)) {
      return NextResponse.json(
        { error: "Transaction is not in a dispute-eligible state" },
        { status: 400 }
      )
    }

    // Ensure disputeFault is valid
    const validFaults = ["SELLER_FAULT", "BUYER_FAULT"]
    if (!validFaults.includes(disputeFault)) {
      return NextResponse.json(
        { error: "Invalid disputeFault value" },
        { status: 400 }
      )
    }

    let refundAmount: number
    let refundDescription: string
    let sellerPayout: number

    // --- Seller Fault: wrong or damaged item ---
    if (disputeFault === "SELLER_FAULT") {
      // Refund 100% of escrow (Item Amount + Waybill Fee) back to Buyer
      refundAmount = transaction.totalEscrow
      sellerPayout = 0

      // Trigger Paystack Refund API (POST /refund)
      try {
        await axios.post(
          "https://api.paystack.co/refund",
          {
            transaction_id: transaction.transactionRef, // or the Paystack charge authorization code
            amount: Math.round(refundAmount * 100), // Paystack uses kobo
            reason: reason || "Seller fault - wrong/damaged item refund",
            refund_code: undefined, // Will be generated by Paystack
          },
          {
            headers: {
              Authorization: `Bearer ${process.env.PAYSTACK_SECRET_KEY}`,
              "Content-Type": "application/json",
            },
          }
        )
      } catch (refundError) {
        console.error("Paystack refund error:", refundError)
        // Continue with DB update even if payment refund fails
      }
    }

    // --- Buyer Fault: change of mind or unreachable ---
    else if (disputeFault === "BUYER_FAULT") {
      // Deduct return waybill fee from locked escrow
      // Return remaining balance to Buyer
      // Transfer return waybill payout to Seller / Logistics

      // Calculate: waybill fee is typically a portion of total escrow
      // For TrustShip: waybillAmount is separate from itemAmount
      // We'll return itemAmount to Seller (since buyer changed mind), 
      // and waybillAmount is retained as return fee or returned based on policy

      // Simplified: Return (itemAmount - platformFee) to Buyer,
      // Transfer waybillAmount to Seller as return fee.
      // Or more commonly: Return full escrow minus a small penalty.

      // For this implementation:
      // - Deduct a 10% return fee from escrow (minimum amount)
      // - Return remaining balance to Buyer
      // - Transfer remaining to Seller

      const returnFee = Math.max(transaction.totalEscrow * 0.1, 50) // min 50 NGN return fee
      refundAmount = transaction.totalEscrow - returnFee
      sellerPayout = returnFee // Seller gets the return fee

      try {
        await axios.post(
          "https://api.paystack.co/refund",
          {
            transaction_id: transaction.transactionRef,
            amount: Math.round(refundAmount * 100),
            reason: reason || "Buyer fault - change of mind refund",
          },
          {
            headers: {
              Authorization: `Bearer ${process.env.PAYSTACK_SECRET_KEY}`,
              "Content-Type": "application/json",
            },
          }
        )
      } catch (refundError) {
        console.error("Paystack refund error:", refundError)
      }
    }

    // Update transaction with dispute resolution
    await prisma.escrowTransaction.update({
      where: { id: transactionId },
      data: {
        status: "REFUNDED",
        disputeFault: disputeFault,
        updatedAt: new Date(),
        // Store payout split info if needed
      },
    })

    // --- Notify both parties via WhatsApp ---
    // Common info for both messages
    const transactionRef = transaction.transactionRef
    const totalEscrow = transaction.totalEscrow

    // Buyer notification
    let buyerMessage: string
    if (disputeFault === "SELLER_FAULT") {
      buyerMessage = `🛡️ Dispute resolved: Seller fault confirmed. Full refund of ₦${totalEscrow} is being processed to your account. Reference: ${transactionRef}`
    } else {
      const returnedAmount = Math.round(refundAmount)
      const returnFee = totalEscrow - refundAmount
      buyerMessage = `🛡️ Dispute resolved: Buyer fault. Refund of ₦${returnedAmount} processed (₦${returnFee} return fee applied). Reference: ${transactionRef}`
    }

    if (transaction.buyerPhone) {
      await sendWhatsAppMessage(
        transaction.buyerPhone,
        buyerMessage
      )
    }

    // Seller notification
    let sellerMessage: string
    if (disputeFault === "SELLER_FAULT") {
      sellerMessage = `🛡️ Dispute resolved: Seller fault confirmed. Full escrow of ₦${totalEscrow} refunded to buyer. Your payout: ₦${sellerPayout}. Reference: ${transactionRef}`
    } else {
      sellerMessage = `🛡️ Dispute resolved: Buyer fault. Return fee of ₦${sellerPayout} collected from escrow. Remaining ₦${refundAmount} refunded to buyer. Reference: ${transactionRef}`
    }

    if (transaction.sellerPhone) {
      await sendWhatsAppMessage(
        transaction.sellerPhone,
        sellerMessage
      )
    }

    return NextResponse.json(
      { 
        success: true, 
        data: { 
          transactionId, 
          disputeFault, 
          refundAmount, 
          sellerPayout,
          status: "REFUNDED" 
        } 
      },
      { status: 200 }
    )
  } catch (error) {
    console.error("Dispute endpoint error:", error)
    return NextResponse.json(
      { error: "Dispute resolution failed" },
      { status: 500 }
    )
  }
}